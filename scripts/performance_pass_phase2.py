offer_html = re.sub(r'\s*<meta\s+http-equiv=["\']Cache-Control["\'][^>]*>', '', offer_html, flags=re.I)
offer_html = re.sub(r'\s*<meta\s+http-equiv=["\']Pragma["\'][^>]*>', '', offer_html, flags=re.I)
if '/assets/css/offer-runtime.css' not in offer_html:
    offer_html = offer_html.replace('</head>', '<link rel="stylesheet" href="/assets/css/offer-runtime.css">\n</head>', 1)
