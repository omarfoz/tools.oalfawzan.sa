    qr_js = qr_js.replace("function generate(){renderValue(true)}", "async function generate(){await renderValue(true)}", 1)
    old_download = "function download(){if(!renderValue(false))return;const canvas=output.querySelector('canvas'),img=output.querySelector('img'),a=document.createElement('a');a.href=canvas?canvas.toDataURL('image/png'):img?.src;if(!a.href)return;a.download=`${currentMode==='contact'?'vcard':'qr'}-${new Date().toISOString().slice(0,10)}.png`;document.body.append(a);a.click();a.remove();statusEl.textContent=STRINGS[currentLang].downloaded}"
