from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

# Consolidate the shared runtime CSS so every tool needs one shared stylesheet
# instead of four/five separate render-blocking requests.
shared_parts = [
    ROOT / 'assets/css/platform.css',
    ROOT / 'assets/css/home-parity.css',
    ROOT / 'assets/css/design-system.css',
    ROOT / 'assets/css/design-taste.css',
]
offer_parts = [
    ROOT / 'assets/css/platform.css',
    ROOT / 'assets/css/home-parity.css',
    ROOT / 'assets/css/offer-mobile.css',
    ROOT / 'assets/css/design-system.css',
    ROOT / 'assets/css/design-taste.css',
]

def bundle(paths, label):
    return f'/* {label} — generated by performance pass. */\n' + '\n'.join(p.read_text(encoding='utf-8') for p in paths)

(ROOT / 'assets/css/tool-runtime.css').write_text(bundle(shared_parts, 'Shared tool runtime'), encoding='utf-8')
(ROOT / 'assets/css/offer-runtime.css').write_text(bundle(offer_parts, 'Offer runtime'), encoding='utf-8')

pages = [
    'json-formatter/index.html',
    'loan-calculator/index.html',
    'qr-generator/index.html',
    'stock-analysis-dashboard/index.html',
    'time/index.html',
    'wheel-of-names/index.html',
]
shared_hrefs = [
    '/assets/css/platform.css',
    '/assets/css/home-parity.css',
    '/assets/css/design-system.css',
    '/assets/css/design-taste.css',
]

def remove_css_link(html, href):
    return re.sub(rf'\s*<link[^>]+href=["\']{re.escape(href)}(?:\?[^"\']*)?["\'][^>]*>', '', html, flags=re.I)

for rel in pages:
    path = ROOT / rel
    html = path.read_text(encoding='utf-8')
    for href in shared_hrefs:
        html = remove_css_link(html, href)
    if '/assets/css/tool-runtime.css' not in html:
        html = html.replace('</head>', '<link rel="stylesheet" href="/assets/css/tool-runtime.css">\n</head>', 1)
    path.write_text(html, encoding='utf-8')

# Offer gets an exact-order bundle including its mobile compatibility layer.
